// npm run gen:voice — scans assets/audio/lines/*.m4a and writes
// src/audio/voiceManifest.generated.ts, a static require() map of the recorded Bella clips.
// A line with no clip falls back to expo-speech. Re-run whenever clips land.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const LINES = join(ROOT, 'assets', 'audio', 'lines');
const OUT = join(ROOT, 'src', 'audio', 'voiceManifest.generated.ts');

export function buildVoiceManifest() {
  const clips = existsSync(LINES) ? readdirSync(LINES).filter((f) => f.endsWith('.m4a')).sort() : [];
  return [
    '// GENERATED by scripts/gen-voice-manifest.mjs (npm run gen:voice). Do not edit by hand.',
    '/* eslint-disable */',
    '',
    `/** ${clips.length} recorded line clips (assets/audio/lines/<id>.m4a), by line id. */`,
    'export const LINE_CLIPS: Readonly<Record<string, number>> = {',
    ...clips.map((f) => `  '${f.slice(0, -4)}': require('../../assets/audio/lines/${f}'),`),
    '};',
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const src = buildVoiceManifest();
  const old = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (old === src) console.log('voice manifest is up to date');
  else {
    writeFileSync(OUT, src);
    console.log(`wrote ${relative(ROOT, OUT)}`);
  }
}
