// npm run gen:art — scans assets/art/** and writes src/art/manifest.generated.ts, a static
// require() map (Metro only bundles static requires). Re-run whenever art lands.
//
// Ids are the path under assets/art/ without the extension: 'plush/bear/round/head_mask',
// 'ui/decor/wall_charm_heart_cross'. PNGs go in ART_IMAGES; JSON files (anchors.json,
// scenes.json, accessories.json) go in ART_DATA. Other files (ART_CREDITS.md) are skipped.
import { readdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { join, relative, dirname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ART = join(ROOT, 'assets', 'art');
const OUT = join(ROOT, 'src', 'art', 'manifest.generated.ts');

function walk(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) => (d.isDirectory() ? walk(join(dir, d.name)) : [join(dir, d.name)]));
}

/** The manifest source for the current art folder (exported for the staleness test). */
export function buildManifest() {
  const files = walk(ART)
    .map((p) => relative(ART, p).split(sep).join('/'))
    .sort();
  const pngs = files.filter((f) => f.endsWith('.png'));
  const jsons = files.filter((f) => f.endsWith('.json'));
  const line = (f, ext) => `  '${f.slice(0, -ext.length)}': require('../../assets/art/${f}'),`;
  return [
    '// GENERATED by scripts/gen-art-manifest.mjs (npm run gen:art). Do not edit by hand.',
    '/* eslint-disable */',
    '',
    `/** ${pngs.length} images under assets/art/, by id (path without .png). */`,
    'export const ART_IMAGES: Readonly<Record<string, number>> = {',
    ...pngs.map((f) => line(f, '.png')),
    '};',
    '',
    `/** ${jsons.length} data files under assets/art/, by id (path without .json). */`,
    'export const ART_DATA: Readonly<Record<string, unknown>> = {',
    ...jsons.map((f) => line(f, '.json')),
    '};',
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const src = buildManifest();
  const old = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (old === src) console.log('art manifest is up to date');
  else {
    writeFileSync(OUT, src);
    console.log(`wrote ${relative(ROOT, OUT)}`);
  }
}
