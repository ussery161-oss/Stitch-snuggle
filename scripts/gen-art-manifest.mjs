// npm run gen:art — scans assets/art/** and writes:
//  - src/art/manifest.generated.ts: a static require() map (Metro only bundles static requires);
//  - src/art/bounds.generated.ts: the visible bounds (alpha > 0) of every plush layer, so the app
//    keeps only the cropped part of each 1024×1024 layer in memory (a full set is ~56 layers).
// Re-run whenever art lands.
//
// Ids are the path under assets/art/ without the extension: 'plush/bear/round/head_mask',
// 'ui/decor/wall_charm_heart_cross'. PNGs go in ART_IMAGES; JSON files (anchors.json,
// scenes.json, accessories.json) go in ART_DATA. Other files (ART_CREDITS.md) are skipped.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ART = join(ROOT, 'assets', 'art');
const OUT = join(ROOT, 'src', 'art', 'manifest.generated.ts');
const OUT_BOUNDS = join(ROOT, 'src', 'art', 'bounds.generated.ts');

function walk(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) => (d.isDirectory() ? walk(join(dir, d.name)) : [join(dir, d.name)]));
}

export function artFiles() {
  return walk(ART)
    .map((p) => relative(ART, p).split(sep).join('/'))
    .sort();
}

/** The manifest source for the current art folder (exported for the staleness test). */
export function buildManifest() {
  const files = artFiles();
  const pngs = files.filter((f) => f.endsWith('.png'));
  const jsons = files.filter((f) => f.endsWith('.json'));
  const line = (f, ext) => `  '${f.slice(0, -ext.length)}': require('../../assets/art/${f}'),`;
  return [
    '// GENERATED by scripts/gen-art-manifest.mjs (npm run gen:art). Do not edit by hand.',
    '/* eslint-disable */',
    '',
    `/** ${pngs.length} images under assets/art/, by id (path without .png). */`,
    'export const ART_IMAGES: Readonly<Record<string, number>> = {',
    ...pngs.map((f) => line(f, '.png')),
    '};',
    '',
    `/** ${jsons.length} data files under assets/art/, by id (path without .json). */`,
    'export const ART_DATA: Readonly<Record<string, unknown>> = {',
    ...jsons.map((f) => line(f, '.json')),
    '};',
    '',
  ].join('\n');
}

/** Plush layer files whose bounds are recorded. */
export function boundedFiles() {
  return artFiles().filter((f) => f.startsWith('plush/') && f.endsWith('.png'));
}

let ck = null;
async function canvasKit() {
  if (ck) return ck;
  const require = createRequire(import.meta.url);
  const dir = dirname(require.resolve('canvaskit-wasm/bin/full/canvaskit.js'));
  const init = require('canvaskit-wasm/bin/full/canvaskit.js');
  ck = await init({ locateFile: (f) => join(dir, f) });
  return ck;
}

/** [x, y, w, h] of the pixels with alpha > 0 (a 2 px margin for filtering), or [0,0,0,0] if empty. */
export async function alphaBounds(file) {
  const CK = await canvasKit();
  const img = CK.MakeImageFromEncoded(readFileSync(join(ART, file)));
  const w = img.width();
  const h = img.height();
  const px = img.readPixels(0, 0, { width: w, height: h, colorType: CK.ColorType.RGBA_8888, alphaType: CK.AlphaType.Unpremul, colorSpace: CK.ColorSpace.SRGB });
  img.delete();
  let x0 = w, y0 = h, x1 = -1, y1 = -1;
  for (let y = 0; y < h; y++) {
    const row = y * w * 4;
    for (let x = 0; x < w; x++) {
      if (px[row + x * 4 + 3] > 0) {
        if (x < x0) x0 = x;
        if (x > x1) x1 = x;
        if (y < y0) y0 = y;
        if (y > y1) y1 = y;
      }
    }
  }
  if (x1 < 0) return [0, 0, 0, 0];
  const m = 2;
  x0 = Math.max(0, x0 - m);
  y0 = Math.max(0, y0 - m);
  x1 = Math.min(w - 1, x1 + m);
  y1 = Math.min(h - 1, y1 + m);
  return [x0, y0, x1 - x0 + 1, y1 - y0 + 1];
}

export function boundsSource(entries) {
  return [
    '// GENERATED by scripts/gen-art-manifest.mjs (npm run gen:art). Do not edit by hand.',
    '/* eslint-disable */',
    '',
    `/** Visible bounds [x, y, w, h] on the 1024 canvas of ${entries.length} plush layers, by id. */`,
    'export const ART_BOUNDS: Readonly<Record<string, readonly [number, number, number, number]>> = {',
    ...entries.map(([f, b]) => `  '${f.slice(0, -4)}': [${b.join(', ')}],`),
    '};',
    '',
  ].join('\n');
}

function writeIfChanged(file, src) {
  const old = existsSync(file) ? readFileSync(file, 'utf8') : '';
  if (old === src) console.log(`${relative(ROOT, file)} is up to date`);
  else {
    writeFileSync(file, src);
    console.log(`wrote ${relative(ROOT, file)}`);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeIfChanged(OUT, buildManifest());
  const entries = [];
  for (const f of boundedFiles()) entries.push([f, await alphaBounds(f)]);
  writeIfChanged(OUT_BOUNDS, boundsSource(entries));
}
