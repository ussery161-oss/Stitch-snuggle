// npm run gen:credits — turns assets/CREDITS.md's "Sources" table into
// src/config/credits.generated.ts for the Credits page (Metro can't bundle a .md file as text).
// Web addresses are kept as plain text without their scheme: the app has no links and no network.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src', 'config', 'credits.generated.ts');

export function buildCredits() {
  const md = readFileSync(join(ROOT, 'assets', 'CREDITS.md'), 'utf8');
  const section = md.slice(md.indexOf('## Sources'), md.indexOf('\n## ', md.indexOf('## Sources') + 3));
  const rows = section
    .split('\n')
    .filter((l) => l.startsWith('|') && !/^\|\s*-/.test(l) && !/^\|\s*Asset\s*\|/.test(l))
    .map((l) =>
      l
        .split('|')
        .slice(1, -1)
        .map((c) => c.trim().replace(/\*\*/g, '').replace(/`/g, '').replace(/https?:\/\//g, '')),
    );
  const items = rows.map(([asset, author, license, source]) => ({ asset, author, license, source }));
  return [
    '// GENERATED by scripts/gen-credits.mjs (npm run gen:credits) from assets/CREDITS.md. Do not edit by hand.',
    '/* eslint-disable */',
    '',
    'export interface CreditRow { asset: string; author: string; license: string; source: string }',
    '',
    `export const CREDIT_ROWS: readonly CreditRow[] = ${JSON.stringify(items, null, 2)};`,
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const src = buildCredits();
  const old = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (old !== src) writeFileSync(OUT, src);
  console.log(old === src ? 'credits are up to date' : 'wrote src/config/credits.generated.ts');
}
